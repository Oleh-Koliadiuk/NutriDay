export function setLanguage(lang) {
  const current = translations[lang] || translations.uk;
  const allText = document.querySelectorAll("[data-i18n]");
  allText.forEach((node) => {
    const key = node.dataset.i18n;
    if (key && current[key]) {
      node.textContent = current[key];
    }
  });

  const placeholders = document.querySelectorAll("[data-i18n-placeholder]");
  placeholders.forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (key && current[key]) {
      node.placeholder = current[key];
    }
  });

  document.documentElement.lang = lang;
  localStorage.setItem("calorie_lang", lang);

  const selector = document.getElementById("language-select");
  if (selector) selector.value = lang;
  window.dispatchEvent(new Event("calorie:language-changed"));
}

export function t(key, values = {}) {
  const lang =
    localStorage.getItem("calorie_lang") ||
    document.documentElement.lang ||
    "uk";
  let value = translations[lang]?.[key] ?? translations.uk[key] ?? key;
  for (const [name, replacement] of Object.entries(values)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}
